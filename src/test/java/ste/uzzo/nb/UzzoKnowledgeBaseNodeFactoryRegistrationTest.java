package ste.uzzo.nb;

import java.io.InputStream;
import java.util.LinkedHashSet;
import java.util.Set;
import javax.xml.parsers.DocumentBuilderFactory;
import org.junit.jupiter.api.Test;
import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.NodeList;

import static org.assertj.core.api.BDDAssertions.then;

/**
 * Guards the registration of the node factory. {@code NodeFactory.Registration}
 * has source retention, so the check runs against the layer generated by its
 * annotation processor.
 */
class UzzoKnowledgeBaseNodeFactoryRegistrationTest {

    private static final String INSTANCE_FILE = "ste-uzzo-nb-UzzoKnowledgeBaseNodeFactory.instance";

    private static final Set<String> CORE_PROJECT_TYPES = Set.of(
            "org-netbeans-modules-maven",
            "org-netbeans-modules-java-j2seproject",
            "org-netbeans-modules-java-j2semodule",
            "org-netbeans-modules-ant-freeform",
            "org-netbeans-modules-gradle",
            "org-netbeans-modules-web-project",
            "org-netbeans-modules-web-clientproject",
            "org-netbeans-modules-php-project",
            "org-netbeans-modules-j2ee-clientproject",
            "org-netbeans-modules-j2ee-ejbjarproject",
            "org-netbeans-modules-j2ee-earproject",
            "org-netbeans-modules-apisupport-project",
            "org-netbeans-modules-apisupport-project-suite");

    @Test
    void factory_is_registered_for_every_extensible_project_type() throws Exception {
        Set<String> registered = registeredProjectTypes();

        then(registered)
                .as("the factory must not be limited to Maven projects")
                .containsAll(CORE_PROJECT_TYPES);
    }

    @Test
    void registration_keeps_the_factory_at_the_same_position() throws Exception {
        Document layer = generatedLayer();
        NodeList files = layer.getElementsByTagName("file");
        boolean found = false;
        for (int i = 0; i < files.getLength(); i++) {
            Element file = (Element) files.item(i);
            if (INSTANCE_FILE.equals(file.getAttribute("name"))) {
                Element position = (Element) file.getElementsByTagName("attr").item(0);
                then(position.getAttribute("name")).isEqualTo("position");
                then(position.getAttribute("intvalue")).isEqualTo("50");
                found = true;
            }
        }
        then(found).as("no %s in the generated layer", INSTANCE_FILE).isTrue();
    }

    private static Set<String> registeredProjectTypes() throws Exception {
        Set<String> types = new LinkedHashSet<>();
        NodeList files = generatedLayer().getElementsByTagName("file");
        for (int i = 0; i < files.getLength(); i++) {
            Element file = (Element) files.item(i);
            if (INSTANCE_FILE.equals(file.getAttribute("name"))) {
                Element nodes = (Element) file.getParentNode();
                Element project = (Element) nodes.getParentNode();
                types.add(project.getAttribute("name"));
            }
        }
        return types;
    }

    private static Document generatedLayer() throws Exception {
        DocumentBuilderFactory factory = DocumentBuilderFactory.newInstance();
        // The DOCTYPE points at netbeans.org: never fetch it in a unit test.
        factory.setFeature("http://apache.org/xml/features/nonvalidating/load-external-dtd", false);
        try (InputStream in = UzzoKnowledgeBaseNodeFactoryRegistrationTest.class
                .getResourceAsStream("/META-INF/generated-layer.xml")) {
            then(in).as("missing META-INF/generated-layer.xml").isNotNull();
            return factory.newDocumentBuilder().parse(in);
        }
    }
}
